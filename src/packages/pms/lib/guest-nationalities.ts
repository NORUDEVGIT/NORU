export function nationalityLabel(code: string): string {
  return NATIONALITY_BY_CODE[code] ?? "";
}

export const GUEST_NATIONALITY_OPTIONS = ISO_COUNTRIES.map((country) => ({
  value: nationalityLabel(country.code) || country.name,
  label: nationalityLabel(country.code) || country.name,
}));

export function nationalityValueForStored(stored: string): string {
  const trimmed = stored.trim();
  if (!trimmed) return "";
  const known = GUEST_NATIONALITY_OPTIONS.find(
    (option) => option.value.localeCompare(trimmed, undefined, { sensitivity: "accent" }) === 0,
  );
  if (known) return known.value;
  const code = countryCodeFromInput(trimmed);
  const label = code ? nationalityLabel(code) : "";
  return label || trimmed;
}
