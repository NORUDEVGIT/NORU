export const GB_COUNTRIES = ["England", "Scotland", "Wales", "Northern Ireland"] as const;

const COUNTRY_BY_CODE = new Map(ISO_COUNTRIES.map((row) => [row.code, row]));
const COUNTRY_BY_NAME = new Map(ISO_COUNTRIES.map((row) => [row.name.toLowerCase(), row]));

export function countryFromInput(value: string): IsoCountry | undefined {
  const trimmed = value.trim();
  if (!trimmed) return undefined;
  if (trimmed.length === 2) return COUNTRY_BY_CODE.get(trimmed.toUpperCase());
  return COUNTRY_BY_NAME.get(trimmed.toLowerCase());
}

export function countryCodeFromInput(value: string): string {
  return countryFromInput(value)?.code ?? "";
}

export function countryNameFromInput(value: string): string {
  return countryFromInput(value)?.name ?? value.trim();
}

export function regionsForCountry(country: string): readonly string[] {
  const code = countryCodeFromInput(country);
  if (code === "ET") return ETHIOPIA_REGIONS;
  if (code === "KE") return KENYA_COUNTIES;
  if (code === "US") return US_STATES;
  if (code === "GB") return GB_COUNTRIES;
  return [];
}

export function hasRegionCatalogue(country: string): boolean {
  return regionsForCountry(country).length > 0;
}

export function isRegionValidForCountry(country: string, region: string): boolean {
  const list = regionsForCountry(country);
  if (list.length === 0) return Boolean(region.trim());
  return list.includes(region as never);
}

export type AddressFieldKey =
  | "addressZone"
  | "addressSubcity"
  | "addressWoreda"
  | "addressKebele"
  | "address"
  | "addressHouseNo"
  | "postcode"
  | "nearbyLandmark";

export type AddressLayout = {
  code: string;
  regionLabel: string;
  regionMode: "select" | "text";
  extras: { key: AddressFieldKey; label: string; helper?: string }[];
};

export function addressLayoutForCountry(country: string): AddressLayout {
  const code = countryCodeFromInput(country);
  if (code === "ET") {
    return {
      code,
      regionLabel: "Region / State",
      regionMode: "select",
      extras: [
        { key: "addressZone", label: "Zone" },
        { key: "addressSubcity", label: "Sub-City / District" },
        { key: "addressWoreda", label: "Woreda", helper: "District-level unit" },
        { key: "addressKebele", label: "Kebele", helper: "Neighbourhood / kebele unit" },
        { key: "address", label: "Street / Area Name" },
        { key: "addressHouseNo", label: "Building / Landmark" },
      ],
    };
  }
  if (code === "GB") {
    return {
      code,
      regionLabel: "Region",
      regionMode: "select",
      extras: [
        { key: "addressSubcity", label: "County" },
        { key: "postcode", label: "Postcode" },
        { key: "address", label: "Street / Area" },
        { key: "addressHouseNo", label: "Building" },
      ],
    };
  }
  if (code === "US") {
    return {
      code,
      regionLabel: "State",
      regionMode: "select",
      extras: [
        { key: "postcode", label: "ZIP Code" },
        { key: "address", label: "Street" },
        { key: "addressHouseNo", label: "Building" },
      ],
    };
  }
  if (code === "KE") {
    return {
      code,
      regionLabel: "County / Region",
      regionMode: "select",
      extras: [
        { key: "addressSubcity", label: "Sub-County" },
        { key: "postcode", label: "Postal Code" },
        { key: "address", label: "Street / Area" },
        { key: "addressHouseNo", label: "Building / Landmark" },
      ],
    };
  }
  return {
    code,
    regionLabel: "Region / State",
    regionMode: hasRegionCatalogue(country) ? "select" : "text",
    extras: [
      { key: "postcode", label: "Postal Code" },
      { key: "address", label: "Street / Area" },
      { key: "addressHouseNo", label: "Building / Landmark" },
    ],
  };
}

export function clearDependentGeography<T extends {
  addressRegion: string;
  addressZone: string;
  addressWoreda: string;
  addressKebele: string;
  addressSubcity: string;
  city: string;
}>(draft: T): T {
  return {
    ...draft,
    addressRegion: "",
    addressZone: "",
    addressWoreda: "",
    addressKebele: "",
    addressSubcity: "",
    city: "",
  };
}

export function isValidLatitude(value: string): boolean {
  if (!value.trim()) return true;
  const n = Number(value);
  return Number.isFinite(n) && n >= -90 && n <= 90;
}

export function isValidLongitude(value: string): boolean {
  if (!value.trim()) return true;
  const n = Number(value);
  return Number.isFinite(n) && n >= -180 && n <= 180;
}

export function isValidHttpUrl(value: string): boolean {
  if (!value.trim()) return true;
  try {
    const parsed = new URL(value.trim());
    return parsed.protocol === "http:" || parsed.protocol === "https:";
  } catch {
    return false;
  }
}
